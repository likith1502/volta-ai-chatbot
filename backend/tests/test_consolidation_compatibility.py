def test_shim_symbol_equivalence(shim_mod, dest_mod, symbol_name):
    """Verify symbol re-exported from shim module matches destination module."""
    shim_module = import_module(shim_mod)
    dest_module = import_module(dest_mod)
    assert hasattr(shim_module, symbol_name), f"Shim {shim_mod} missing {symbol_name}"
    assert hasattr(dest_module, symbol_name), f"Dest {dest_mod} missing {symbol_name}"
    shim_sym = getattr(shim_module, symbol_name)
    dest_sym = getattr(dest_module, symbol_name)
    if isinstance(shim_sym, type) or callable(shim_sym):
        assert shim_sym is dest_sym, f"Identity mismatch for {symbol_name} between {shim_mod} and {dest_mod}"
    else:
        assert shim_sym == dest_sym, f"Value mismatch for {symbol_name} between {shim_mod} and {dest_mod}"